-- Flyway V2: Study Plans, Tasks, Immutable Submissions, AI Evaluations, Sources, Jobs, Cache, and Usage Logs

CREATE TABLE study_plans (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id BIGINT NOT NULL,
    target_date DATE NOT NULL,
    timetable_id BIGINT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT uq_study_plans_student_date UNIQUE (student_id, target_date),
    CONSTRAINT fk_study_plans_student FOREIGN KEY (student_id) REFERENCES student_profiles (id) ON DELETE CASCADE,
    CONSTRAINT fk_study_plans_timetable FOREIGN KEY (timetable_id) REFERENCES timetables (id)
);

CREATE TABLE study_tasks (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    plan_id BIGINT NOT NULL,
    subject_id BIGINT NOT NULL,
    task_type VARCHAR(20) NOT NULL CHECK (task_type IN ('REVIEW', 'PREVIEW')),
    status VARCHAR(30) NOT NULL DEFAULT 'NOT_STARTED' CHECK (
        status IN ('NOT_STARTED', 'IN_PROGRESS', 'SUBMITTED', 'EVALUATING', 'EVALUATED', 'EVALUATION_FAILED', 'BLOCKED')
    ),
    revision_count INT NOT NULL DEFAULT 0 CHECK (revision_count BETWEEN 0 AND 2),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT uq_study_tasks_plan_subject_type UNIQUE (plan_id, subject_id, task_type),
    CONSTRAINT fk_study_tasks_plan FOREIGN KEY (plan_id) REFERENCES study_plans (id) ON DELETE CASCADE,
    CONSTRAINT fk_study_tasks_subject FOREIGN KEY (subject_id) REFERENCES subjects (id)
);

CREATE INDEX idx_study_tasks_plan ON study_tasks (plan_id);

CREATE TABLE study_submissions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    task_id BIGINT NOT NULL,
    version INT NOT NULL CHECK (version BETWEEN 1 AND 3),
    is_current BOOLEAN NOT NULL DEFAULT TRUE,
    lesson_title VARCHAR(255) NOT NULL,
    content TEXT NOT NULL,
    char_count INT NOT NULL CHECK (char_count BETWEEN 850 AND 2000),
    idempotency_key VARCHAR(64) NOT NULL,
    submitted_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT uq_study_submissions_task_version UNIQUE (task_id, version),
    CONSTRAINT uq_study_submissions_idempotency UNIQUE (idempotency_key),
    CONSTRAINT fk_study_submissions_task FOREIGN KEY (task_id) REFERENCES study_tasks (id) ON DELETE CASCADE
);

CREATE INDEX idx_study_submissions_task_current ON study_submissions (task_id, is_current);

CREATE TABLE ai_evaluations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    submission_id BIGINT NOT NULL,
    accuracy VARCHAR(30) NOT NULL CHECK (accuracy IN ('CORRECT', 'PARTIALLY_CORRECT', 'INCORRECT', 'UNVERIFIABLE')),
    completeness VARCHAR(30) NOT NULL CHECK (completeness IN ('COMPLETE', 'INCOMPLETE', 'UNDETERMINED')),
    overall_status VARCHAR(30) NOT NULL CHECK (overall_status IN ('GOOD', 'NEEDS_IMPROVEMENT', 'INCORRECT', 'INSUFFICIENT_EVIDENCE')),
    feedback VARCHAR(600) NOT NULL,
    incorrect_points JSONB NOT NULL DEFAULT '[]'::jsonb,
    missing_points JSONB NOT NULL DEFAULT '[]'::jsonb,
    confidence VARCHAR(20) NOT NULL CHECK (confidence IN ('HIGH', 'MEDIUM', 'LOW')),
    raw_sanitized_response JSONB,
    evaluated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT uq_ai_evaluations_submission UNIQUE (submission_id),
    CONSTRAINT fk_ai_evaluations_submission FOREIGN KEY (submission_id) REFERENCES study_submissions (id) ON DELETE CASCADE
);

CREATE TABLE source_references (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    evaluation_id BIGINT NOT NULL,
    title VARCHAR(255) NOT NULL,
    url VARCHAR(1000) NOT NULL,
    snippet TEXT,
    retrieved_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT fk_source_references_evaluation FOREIGN KEY (evaluation_id) REFERENCES ai_evaluations (id) ON DELETE CASCADE
);

CREATE INDEX idx_source_references_evaluation ON source_references (evaluation_id);

CREATE TABLE evaluation_jobs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    submission_id BIGINT NOT NULL,
    idempotency_key VARCHAR(64) NOT NULL,
    status VARCHAR(30) NOT NULL DEFAULT 'PENDING' CHECK (status IN ('PENDING', 'RUNNING', 'SUCCEEDED', 'FAILED')),
    attempts INT NOT NULL DEFAULT 0 CHECK (attempts >= 0),
    max_attempts INT NOT NULL DEFAULT 3 CHECK (max_attempts >= 1),
    next_retry_at TIMESTAMPTZ,
    last_error TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT uq_evaluation_jobs_submission UNIQUE (submission_id),
    CONSTRAINT uq_evaluation_jobs_idempotency UNIQUE (idempotency_key),
    CONSTRAINT fk_evaluation_jobs_submission FOREIGN KEY (submission_id) REFERENCES study_submissions (id) ON DELETE CASCADE
);

CREATE INDEX idx_evaluation_jobs_polling ON evaluation_jobs (status, next_retry_at);

CREATE TABLE ai_usage_logs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    job_id BIGINT NOT NULL,
    provider VARCHAR(50) NOT NULL,
    model VARCHAR(80) NOT NULL,
    input_tokens INT NOT NULL DEFAULT 0,
    output_tokens INT NOT NULL DEFAULT 0,
    search_count INT NOT NULL DEFAULT 0,
    cache_hit BOOLEAN NOT NULL DEFAULT FALSE,
    estimated_cost_usd NUMERIC(10, 6) NOT NULL DEFAULT 0,
    latency_ms INT NOT NULL DEFAULT 0,
    status VARCHAR(30) NOT NULL,
    error_code VARCHAR(50),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT fk_ai_usage_logs_job FOREIGN KEY (job_id) REFERENCES evaluation_jobs (id) ON DELETE CASCADE
);

CREATE INDEX idx_ai_usage_logs_job ON ai_usage_logs (job_id);

CREATE TABLE knowledge_cache (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cache_key VARCHAR(255) NOT NULL,
    grade INT NOT NULL CHECK (grade BETWEEN 1 AND 12),
    subject_code VARCHAR(20) NOT NULL,
    normalized_lesson_title VARCHAR(255) NOT NULL,
    sources_json JSONB NOT NULL DEFAULT '[]'::jsonb,
    cache_allowed BOOLEAN NOT NULL DEFAULT TRUE,
    policy_version VARCHAR(20) NOT NULL DEFAULT 'v1',
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    expires_at TIMESTAMPTZ NOT NULL,
    CONSTRAINT uq_knowledge_cache_key UNIQUE (cache_key)
);

CREATE INDEX idx_knowledge_cache_expires ON knowledge_cache (expires_at);
