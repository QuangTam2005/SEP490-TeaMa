CREATE TABLE timetables (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id BIGINT NOT NULL,
    effective_date DATE NOT NULL,
    version INT NOT NULL DEFAULT 1 CHECK (version >= 1),
    status VARCHAR(20) NOT NULL DEFAULT 'ACTIVE' CHECK (status IN ('ACTIVE', 'ARCHIVED')),
    updated_by_user_id BIGINT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT uq_timetables_student_version UNIQUE (student_id, version),
    CONSTRAINT fk_timetables_student FOREIGN KEY (student_id) REFERENCES student_profiles (id) ON DELETE CASCADE,
    CONSTRAINT fk_timetables_updated_by FOREIGN KEY (updated_by_user_id) REFERENCES users (id)
);

CREATE INDEX idx_timetables_student_status ON timetables (student_id, status);

CREATE TABLE timetable_entries (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    timetable_id BIGINT NOT NULL,
    weekday INT NOT NULL CHECK (weekday BETWEEN 1 AND 7),
    subject_id BIGINT NOT NULL,
    period_note VARCHAR(120),
    CONSTRAINT fk_timetable_entries_timetable FOREIGN KEY (timetable_id) REFERENCES timetables (id) ON DELETE CASCADE,
    CONSTRAINT fk_timetable_entries_subject FOREIGN KEY (subject_id) REFERENCES subjects (id)
);

CREATE INDEX idx_timetable_entries_lookup ON timetable_entries (timetable_id, weekday, subject_id);
