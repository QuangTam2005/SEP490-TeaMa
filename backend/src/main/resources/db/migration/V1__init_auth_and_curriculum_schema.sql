-- Flyway V1: Authentication, Guardian Link, Grade 6 Fixed Subjects, and Versioned Timetable Schema

CREATE TABLE users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email VARCHAR(255) NOT NULL,
    password_hash VARCHAR(255) NOT NULL,
    full_name VARCHAR(150) NOT NULL,
    role VARCHAR(20) NOT NULL CHECK (role IN ('STUDENT', 'GUARDIAN')),
    status VARCHAR(20) NOT NULL DEFAULT 'ACTIVE' CHECK (status IN ('ACTIVE', 'DISABLED')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT uq_users_email UNIQUE (email)
);

CREATE UNIQUE INDEX uq_users_email_lower ON users (LOWER(email));

CREATE TABLE student_profiles (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    display_name VARCHAR(150) NOT NULL,
    grade INT NOT NULL CHECK (grade BETWEEN 1 AND 12),
    timezone VARCHAR(64) NOT NULL DEFAULT 'Asia/Ho_Chi_Minh',
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT uq_student_profiles_user UNIQUE (user_id),
    CONSTRAINT fk_student_profiles_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE
);

CREATE TABLE guardian_links (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    guardian_user_id BIGINT,
    student_id BIGINT NOT NULL,
    link_code VARCHAR(16) NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'PENDING' CHECK (status IN ('PENDING', 'ACTIVE', 'REVOKED')),
    expires_at TIMESTAMPTZ NOT NULL,
    linked_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT uq_guardian_links_code UNIQUE (link_code),
    CONSTRAINT fk_guardian_links_guardian FOREIGN KEY (guardian_user_id) REFERENCES users (id) ON DELETE CASCADE,
    CONSTRAINT fk_guardian_links_student FOREIGN KEY (student_id) REFERENCES student_profiles (id) ON DELETE CASCADE
);

CREATE INDEX idx_guardian_links_guardian_status ON guardian_links (guardian_user_id, status);
CREATE INDEX idx_guardian_links_student_status ON guardian_links (student_id, status);

CREATE TABLE subjects (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR(20) NOT NULL CHECK (code IN ('MATH', 'LIT', 'ENG', 'SCI', 'HISGEO')),
    name VARCHAR(100) NOT NULL,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT uq_subjects_code UNIQUE (code)
);

