-- Flyway V9: Guardian 2-option quiz bank, daily display settings, daily quiz sessions & answer snapshots

CREATE TABLE daily_quiz_settings (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id BIGINT NOT NULL UNIQUE REFERENCES student_profiles (id) ON DELETE CASCADE,
    enabled BOOLEAN NOT NULL DEFAULT FALSE,
    questions_per_day INT NOT NULL DEFAULT 10 CHECK (questions_per_day BETWEEN 1 AND 50),
    active_weekdays VARCHAR(20) NOT NULL DEFAULT '1,2,3,4,5,6,7',
    selection_mode VARCHAR(30) NOT NULL DEFAULT 'SEQUENTIAL_ROTATION' CHECK (
        selection_mode IN ('SEQUENTIAL_ROTATION', 'RANDOM')
    ),
    shuffle_options BOOLEAN NOT NULL DEFAULT FALSE,
    rotation_cursor INT NOT NULL DEFAULT 0 CHECK (rotation_cursor >= 0),
    updated_by_user_id BIGINT NULL REFERENCES users (id) ON DELETE SET NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE guardian_quiz_questions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id BIGINT NOT NULL REFERENCES student_profiles (id) ON DELETE CASCADE,
    sort_order INT NOT NULL DEFAULT 1 CHECK (sort_order >= 1),
    question_text VARCHAR(500) NOT NULL,
    option_a VARCHAR(250) NOT NULL,
    option_b VARCHAR(250) NOT NULL,
    correct_option VARCHAR(10) NOT NULL CHECK (correct_option IN ('A', 'B')),
    explanation VARCHAR(500) NULL,
    topic_label VARCHAR(80) NULL,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_by_user_id BIGINT NULL REFERENCES users (id) ON DELETE SET NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX idx_guardian_quiz_questions_student_order
    ON guardian_quiz_questions (student_id, is_active, sort_order, id);

CREATE TABLE daily_quiz_sessions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id BIGINT NOT NULL REFERENCES student_profiles (id) ON DELETE CASCADE,
    session_date DATE NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'IN_PROGRESS' CHECK (status IN ('IN_PROGRESS', 'COMPLETED')),
    total_questions INT NOT NULL CHECK (total_questions >= 1),
    answered_count INT NOT NULL DEFAULT 0 CHECK (answered_count >= 0),
    correct_count INT NOT NULL DEFAULT 0 CHECK (correct_count >= 0),
    cycle_start_index INT NOT NULL DEFAULT 0 CHECK (cycle_start_index >= 0),
    cycle_end_index INT NOT NULL DEFAULT 0 CHECK (cycle_end_index >= 0),
    started_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    completed_at TIMESTAMPTZ NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT uq_daily_quiz_sessions_student_date UNIQUE (student_id, session_date)
);

CREATE INDEX idx_daily_quiz_sessions_student_date
    ON daily_quiz_sessions (student_id, session_date DESC);

CREATE TABLE daily_quiz_session_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_id BIGINT NOT NULL REFERENCES daily_quiz_sessions (id) ON DELETE CASCADE,
    question_id BIGINT NULL REFERENCES guardian_quiz_questions (id) ON DELETE SET NULL,
    item_order INT NOT NULL CHECK (item_order >= 1),
    question_text VARCHAR(500) NOT NULL,
    display_option_a VARCHAR(250) NOT NULL,
    display_option_b VARCHAR(250) NOT NULL,
    correct_display_option VARCHAR(10) NOT NULL CHECK (correct_display_option IN ('A', 'B')),
    explanation VARCHAR(500) NULL,
    topic_label VARCHAR(80) NULL,
    selected_option VARCHAR(10) NULL CHECK (selected_option IN ('A', 'B')),
    is_correct BOOLEAN NULL,
    answered_at TIMESTAMPTZ NULL,
    CONSTRAINT uq_daily_quiz_session_items_order UNIQUE (session_id, item_order)
);
